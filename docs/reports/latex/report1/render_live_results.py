#!/usr/bin/env python3
"""Render the measured report section from its archived JSON; no GPU work."""
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
SOURCE = ROOT / 'evidence/report1/2026-11-11-g1-live/summary.json'


def render():
    data = json.loads(SOURCE.read_text())
    assert data['status'] == 'PASS_BOUNDED_MEASUREMENT_AND_PACKET_PARITY'
    assert data['source_inputs_binaries_unchanged']
    assert data['sessions'] == 8 and data['measured_samples_per_style'] == 480
    single = data['single_latency_ms']
    queued = data['queued_delivery_latency_ms']
    constructor = data['constructor_ms']
    first = data['first_frame_ms']
    rows = '\n'.join(
        f"{title} & {single[key]:.6f} & {queued[key]:.6f} " + r'\\'
        for title, key in [('平均', 'mean'), ('p50', 'p50'), ('p95', 'p95'),
                           ('p99', 'p99'), ('最小值', 'min'), ('最大值', 'max')])
    text = r'''% Generated by render_live_results.py; edit the source evidence only via a new run.
本次從固定 \code{3cbaa518f0dc} 的乾淨 detached worktree 重建 runtime，沿用原 engine，不重建模型。另行編譯僅增加 host enqueue／receive timestamps 的 benchmark；runtime 原檔未修改。測試為 HR、G1、Graph ON、NSA／量測框 OFF、result ring=4，使用 MOT17-10-SDP 前 140 幀，每 session 暖機 20 幀、量測 120 幀。Single 與 queued 交替各四次，共八個 fresh sessions、每模式 480 筆暖機後樣本。\cite{live}

\begin{table}[H]
\caption{本次 G1 提交至結果交付延遲，單位 ms}
\small
\noindent\begin{tabularx}{\textwidth}{@{}Yrr@{}}
\toprule
統計 & Single：同幀立即 receive & Queued：四格 ring \\
\midrule
''' + rows + r'''
\bottomrule
\end{tabularx}
\end{table}

''' + (
        f"Queued wall interval 平均為 \\textbf{{{data['queued_wall_interval_ms_per_frame']['mean']:.6f} ms/frame}}，"
        f"換算吞吐為 \\textbf{{{data['queued_throughput_fps']:.3f} FPS}}。"
        f"它與 queued 交付平均 {queued['mean']:.3f} ms、p95 {queued['p95']:.3f} ms 是不同指標；"
        "較深佇列的吞吐不能代替同幀交付時間。\n\n"
    ) + r'''\begin{table}[H]
\caption{本次初始化與首幀時間：八個 fresh sessions，單位 ms}
\small
\noindent\begin{tabularx}{\textwidth}{@{}Yrrr@{}}
\toprule
項目 & 最小值 & 中位數 & 最大值 \\
\midrule
''' + (
        f"Session constructor & {constructor['min']:.3f} & {constructor['median']:.3f} & {constructor['max']:.3f} " + r'\\' + '\n'
        f"首幀 enqueue 至 receive & {first['min']:.3f} & {first['median']:.3f} & {first['max']:.3f} " + r'\\' + '\n'
    ) + r'''\bottomrule
\end{tabularx}
\end{table}

\textbf{一致性與環境。} 八份 140 幀完整 packet stream 逐 byte 相同，包含暖機、未用 rows 與 reserved bytes；source、engine、輸入及 binaries 的量測前後 hashes 均相同。Driver 為 621.14，CUDA 13.4.92、TensorRT 10.16.1.11；與歷史 driver 617.42 不同，不合併樣本、不宣稱跨時段加速。封包相同指本次 sessions 之間的一致性，不是新一次品質驗收。

\textbf{遙測與適用限制。} 每秒一次的 12 筆程序期遙測包含 constructor 與暖機，GPU utilization 平均 46.5\%、最大 100\%，最高溫 68\,°C、功率 139.46 W、顯存 495 MiB；不能當作穩態利用率。只有一序列 prefix 與每模式四次 sessions，JPEG 已預載、未鎖 clocks；每對固定 single 先、queued 後，順序未反平衡。Host timestamp 會有小量成本，所有長尾保留。

\textbf{統計口徑。} 表中 p50／p95／p99 採 nearest-rank，初始化表的中位數則為中間兩值平均。權威逐幀樣本為 \code{*.delivery.csv}，終點是 receive 返回、packet 檢查與複製之前。原 stock harness 的 \code{runs.csv} 與 single CSV 另含後續檢查／複製，並保留原樣；本表不混用兩種口徑。
'''
    (HERE / 'live-results.tex').write_text(text)
    print(json.dumps({'source': str(SOURCE.relative_to(ROOT)),
                      'source_sha256': hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
                      'output': str((HERE / 'live-results.tex').relative_to(ROOT))}, ensure_ascii=False))

    offline_source = ROOT / 'evidence/report1/2026-11-11-g1-offline-e2e/summary.json'
    offline = json.loads(offline_source.read_text())
    assert offline['status'] == 'PASS_BOUNDED_PROCESS_COMPLETION_AND_OUTPUT_PARITY'
    assert offline['source_inputs_binaries_unchanged']
    assert offline['packet_prefix_matches_prior_140_frame_benchmark']
    rows = '\n'.join(
        f"{r['ordinal']} & {r['wall_ms']/1000:.6f} & {r['app_loop_wall_ms']/1000:.6f} " + r'\\'
        for r in offline['run_records'])
    text = r'''% Generated from the independent full-process completion evidence.
本組從外部計時程式即將啟動 \code{track_sequence} 起，量至程序正常退出並由 parent 完成 blocking wait。使用同一乾淨基準、原 engine、HR／G1／Graph／pipelined、四格 ring、NSA OFF；MOT17-10 完整 654 幀，連續三個 fresh processes。沒有修改 CLI 或 runtime，也沒有 profiler。\cite{offline}

\begin{finding}
\textbf{涵蓋的完整離線邊界：} 程式啟動、engine 載入、初始化、全部 JPEG 讀取與處理、drain／close、序列尾插值與 ID 定稿、MOT／packet／motion／設定與 log 寫入，直到程序退出。這是整段序列完成時間。
\end{finding}

\begin{table}[H]
\caption{完整 654 幀離線端到端耗時，單位秒}
\small
\noindent\begin{tabularx}{\textwidth}{@{}Yrr@{}}
\toprule
Fresh process & 外部完整程序時間 & CLI 內部處理迴圈 \\
\midrule
''' + rows + r'''
\midrule
''' + (
        f"平均 & {offline['process_wall_ms']['mean']/1000:.6f} & {offline['app_loop_wall_ms']['mean']/1000:.6f} " + r'\\' + '\n'
    ) + r'''\bottomrule
\end{tabularx}
\end{table}

''' + (
        f"完整程序平均 \\textbf{{{offline['process_wall_ms']['mean']/1000:.3f} 秒／654 幀}}，"
        f"攤提為 {offline['amortized_process_ms_per_frame']['mean']:.6f} ms/frame，"
        f"三次總幀數除以總時間換算為 {offline['aggregate_process_throughput_fps']:.3f} FPS。"
        "這些是包含啟動與尾端輸出的離線完成成本，不能讀作每一幀的交付延遲。"
        f"完整程序與 CLI 內部迴圈平均相差 {offline['process_minus_app_loop_ms']['mean']/1000:.3f} 秒，"
        "包含程序啟動、constructor、close、EOF 定稿與寫檔等成本，不能全數歸因為模型初始化。\n\n"
    ) + r'''\textbf{輸出與保管。} 三次 MOT、完整 packets、motion records 與 resolved config 均逐 byte 相同；全部 654 張輸入、source 與 binary 的前後 hash 相同。完整 packets 的前 140 幀也等於上一組逐幀 benchmark，連接兩種量測範圍的輸出一致性。

\textbf{適用範圍。} 讀檔路徑確實納入，但 preflight hashing 已讀過輸入，作業系統 page cache 未清除，不代表冷磁碟效能。量測包含檔案 write／checked close，不涵蓋 fsync 持久化。只測一序列、三次 fresh processes；沒有相機／網路來源或逐幀最終 MOT 延遲。15 筆程序期遙測的 GPU utilization 平均 72.93\%、最大 100\%，最高 70\,°C、142.17 W、495 MiB；同樣不能當作穩態利用率。
'''
    (HERE / 'offline-e2e.tex').write_text(text)
    print(json.dumps({'source': str(offline_source.relative_to(ROOT)),
                      'source_sha256': hashlib.sha256(offline_source.read_bytes()).hexdigest(),
                      'output': str((HERE / 'offline-e2e.tex').relative_to(ROOT))}, ensure_ascii=False))


if __name__ == '__main__':
    render()
